// native_opensles.cpp -- libOpenSLES for an app's native code, until it is
// ported.
//
// Upstream implements OpenSL ES on its audio mixer (bionic_shim.cpp, "REAL
// OpenSL ES output"). Until that is ported onto audio_engine.h, the engine
// cannot be created, and says so: a missing function's stub returns 0, which
// for slCreateEngine is SL_RESULT_SUCCESS with no engine, and SDL then waits
// on audio that never starts. With an error, engines fall back to silence.
//
// The interface IDs are real, though. libOpenSLES exports each SL_IID_x as a
// variable of type SLInterfaceID, a pointer to the interface's GUID, and code
// that uses OpenSL ES reads them (into the arrays it passes to CreateAudioPlayer
// and GetInterface) as soon as it is loaded. Bound to zeroed memory, every ID
// was a null pointer. The GUID's layout is the same on both sides: fixed-width
// fields, 16 bytes (SLInterfaceID_ in OpenSLES.h):
//
//   time_low 0 (4), time_mid 4 (2), time_hi_and_version 6 (2),
//   clock_seq 8 (2), node 10 (6)
//
// The values and the exported names are AOSP's (frameworks/wilhelm:
// src/OpenSLES_IID.cpp and src/sl_iid.cpp); upstream's bionic_shim.cpp has
// the same values for the nine IDs it defines.

