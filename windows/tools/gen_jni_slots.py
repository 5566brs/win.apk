#!/usr/bin/env python3
"""gen_jni_slots.py -- generate windows/src/jni_slots.inc from a JDK's jni.h.

The guest JNIEnv table (windows/src/guest_jni.cpp) needs one System V entry per
JNINativeInterface_ slot, in table order. Writing ~230 names by hand invites
typos, so the list is generated from the spec header and checked in:

    python3 windows/tools/gen_jni_slots.py $JAVA_HOME/include/jni.h > windows/src/jni_slots.inc

Each slot becomes one X-macro line:
    WINAPK_JNI_RESERVED(index)              a NULL slot
    WINAPK_JNI_PLAIN(Name)                  fixed arguments: forwarded generically
    WINAPK_JNI_CALL(Name, Kind, Type)       C-variadic Call*Method / NewObject
    WINAPK_JNI_CALLV(Name, Kind, Type)      va_list variant of the same
Kind is Virtual, Nonvirtual, Static or NewObject; Type is the Java result type.
"""

import re
import sys

CALL_RE = re.compile(r"^(?:Call(Nonvirtual|Static)?(Object|Boolean|Byte|Char|Short|Int|Long|Float|Double|Void)Method|(NewObject))(V|A)?$")


def main(path):
    text = open(path, encoding="utf-8").read()
    m = re.search(r"struct JNINativeInterface_\s*\{(.*?)\n\};", text, re.S)
    if not m:
        sys.exit("JNINativeInterface_ not found in " + path)
    body = m.group(1)
    # Each slot is either `void *reservedN;` or a function pointer declaration
    # ending in `);`. Split on top-level semicolons.
    decls = [d.strip() for d in body.split(";") if d.strip()]
    out = ["// Generated by windows/tools/gen_jni_slots.py from " + path.split("include/")[-1] +
           " -- do not edit.", "// One line per JNINativeInterface_ slot, in table order."]
    for index, d in enumerate(decls):
        d = " ".join(d.split())
        if re.match(r"void \*reserved\d+$", d):
            out.append("WINAPK_JNI_RESERVED(%d)" % index)
            continue
        name = re.search(r"\(JNICALL \*(\w+)\)", d)
        if not name:
            sys.exit("cannot parse slot %d: %s" % (index, d))
        name = name.group(1)
        call = CALL_RE.match(name)
        if "..." in d:
            kind = "NewObject" if call.group(3) else (call.group(1) or "Virtual")
            rtype = "Object" if call.group(3) else call.group(2)
            out.append("WINAPK_JNI_CALL(%s, %s, %s)" % (name, kind, rtype))
        elif "va_list" in d:
            kind = "NewObject" if call.group(3) else (call.group(1) or "Virtual")
            rtype = "Object" if call.group(3) else call.group(2)
            out.append("WINAPK_JNI_CALLV(%s, %s, %s)" % (name, kind, rtype))
        else:
            out.append("WINAPK_JNI_PLAIN(%s)" % name)
    print("\n".join(out))


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
